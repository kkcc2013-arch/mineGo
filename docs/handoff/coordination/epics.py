def classify(item):
    for prefix, epic in OVERRIDES.items():
        if item['file'].lower().startswith(prefix.lower()):
            return epic
    for eid, _, _, rx in EPICS:
        if re.search(rx, item['title'], re.I):
            return eid
    return None


def main():
    repo = sys.argv[1]
    here = os.path.dirname(os.path.abspath(__file__))
    idx = json.load(open(os.path.join(here, 'req_index.json')))
    open_ = [x for x in idx if x['status'] in ('new', 'partial')]
    epics = {e[0]: dict(id=e[0], name=e[1], wave=e[2], reqs=[]) for e in EPICS}
    unassigned = []
    for x in open_:
        e = classify(x)
        if e:
            epics[e]['reqs'].append(dict(id=x['id'], file=x['file'], title=x['title'], priority=x['priority']))
        else:
            unassigned.append(x)
    json.dump(list(epics.values()), open(os.path.join(here, 'epics.json'), 'w'), ensure_ascii=False, indent=1)
    for e in epics.values():
        print(f"{e['id']} w{e['wave']} {len(e['reqs']):3d}  {e['name']}")
    print('unassigned', len(unassigned))
    for x in unassigned:
        print('  ', x['file'][:60], x['title'][:40])


if __name__ == '__main__':
    main()
